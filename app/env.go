var envDecoderTypes = []reflect.Type{
	reflect.TypeFor[envconfig.DecoderCtx](),
	reflect.TypeFor[encoding.TextUnmarshaler](),
	reflect.TypeFor[json.Unmarshaler](),
	reflect.TypeFor[encoding.BinaryUnmarshaler](),
	reflect.TypeFor[gob.GobDecoder](),
}

type envField struct {
	key         string
	value       string
	required    bool
	hasDefault  bool
	description string
	path        string
	index       []int
	typ         reflect.Type
}

// EnvOption configures environment schema generation and loading.
type EnvOption func(*envOptions)

type envOptions struct {
	prefix string
}

// WithEnvPrefix sets the single root prefix for a hierarchical configuration.
// A trailing underscore is optional. Nested struct field names and explicit
// env segments are appended below that root prefix.
func WithEnvPrefix(prefix string) EnvOption {
	return func(options *envOptions) {
		options.prefix = prefix
	}
}

// EnvTemplate renders a shell-compatible environment template for config.
// Nested struct fields contribute env segments below the optional root prefix.
// The whole schema is validated, including duplicate keys across nested structs.
func EnvTemplate(config any, options ...EnvOption) ([]byte, error) {
	schema, err := buildEnvSchema(config, options...)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.WriteString("# Generated by Plinth. Do not edit by hand.\n\n")
	for _, field := range schema.fields {
		for _, line := range strings.Split(field.description, "\n") {
			if line == "" {
				out.WriteString("#\n")
				continue
			}
			fmt.Fprintf(&out, "# %s\n", line)
		}
		if field.required {
			out.WriteString("# required\n")
		}
		if !field.required && !field.hasDefault {
			fmt.Fprintf(&out, "# %s=\n", field.key)
			continue
		}
		fmt.Fprintf(&out, "%s=%s\n", field.key, quoteEnvValue(field.value))
	}
	return out.Bytes(), nil
}

// LoadEnv validates the complete env schema, decodes the process environment
// into config, and runs the struct's validate tags. Schema validation catches
// duplicate variable names and malformed nesting before any field is changed.
func LoadEnv(ctx context.Context, config any, options ...EnvOption) error {
	schema, err := buildEnvSchema(config, options...)
	if err != nil {
		return err
	}
	value := reflect.ValueOf(config)
	if !value.IsValid() || value.Kind() != reflect.Pointer || value.IsNil() || value.Elem().Kind() != reflect.Struct {
		return fmt.Errorf("config must be a non-nil pointer to a struct")
	}
	root := value.Elem()
	for _, field := range schema.fields {
		if err := loadEnvField(ctx, root, field); err != nil {
			return err
		}
	}
	if err := validateEnvValues(root.Interface(), schema); err != nil {
		return err
	}
	return nil
}

type envSchema struct {
	fields []envField
}

func buildEnvSchema(config any, options ...EnvOption) (envSchema, error) {
	var opts envOptions
	for _, option := range options {
		if option != nil {
			option(&opts)
		}
	}
	prefix, err := normalizeEnvPrefix(opts.prefix)
	if err != nil {
		return envSchema{}, err
	}

	t := reflect.TypeOf(config)
	if t == nil {
		return envSchema{}, fmt.Errorf("config must be a struct or pointer to a struct")
	}
	t, err = derefEnvType(t)
	if err != nil {
		return envSchema{}, fmt.Errorf("config: %w", err)
	}
	if t.Kind() != reflect.Struct {
		return envSchema{}, fmt.Errorf("config must be a struct or pointer to a struct")
	}

	var fields []envField
	seen := map[string]string{}
	visiting := map[reflect.Type]bool{}
	if err := collectEnv(t, prefix, "", nil, &fields, seen, visiting); err != nil {
		return envSchema{}, err
	}
	return envSchema{fields: fields}, nil
}

func collectEnv(t reflect.Type, prefix, path string, index []int, fields *[]envField, seen map[string]string, visiting map[reflect.Type]bool) error {
	t, err := derefEnvType(t)
	if err != nil {
		return envPathError(path, err)
	}
	if t.Kind() != reflect.Struct {
		return nil
	}
	if visiting[t] {
		return envPathError(path, fmt.Errorf("recursive struct type %s", t))
	}
	visiting[t] = true
	defer delete(visiting, t)

	for i := 0; i < t.NumField(); i++ {
		field := t.Field(i)
		fieldPath := field.Name
		if path != "" {
			fieldPath = path + "." + field.Name
		}
		fieldIndex := append(append([]int(nil), index...), i)

		tag, tagged := field.Tag.Lookup("env")
		description, described := field.Tag.Lookup("envdoc")
		if field.PkgPath != "" {
			if tagged {
				return fmt.Errorf("%s: env tag on unexported field", fieldPath)
			}
			if described {
				return fmt.Errorf("%s: envdoc on unexported field", fieldPath)
			}
			continue
		}
		if strings.ContainsRune(description, 0) {
			return fmt.Errorf("%s: envdoc must not contain NUL", fieldPath)
		}
		description = strings.ReplaceAll(description, "\r\n", "\n")
		description = strings.ReplaceAll(description, "\r", "\n")

		name, required, hasDefault, defaultValue, tagPrefix, err := parseEnvTag(tag)
		if err != nil {
			return fmt.Errorf("%s: %w", fieldPath, err)
		}
		if tagged && name == "-" {
			if required || hasDefault || tagPrefix != "" || described {
				return fmt.Errorf("%s: ignored env field cannot have options", fieldPath)
			}
			continue
		}

		fieldType, err := derefEnvType(field.Type)
		if err != nil {
			return envPathError(fieldPath, err)
		}
		if tagPrefix != "" {
			return fmt.Errorf("%s: prefix= is only supported at the config root through app.WithEnvPrefix", fieldPath)
		}
		if fieldType.Kind() == reflect.Struct && !implementsEnvDecoder(fieldType) {
			if required || hasDefault {
				return fmt.Errorf("%s: nested struct cannot declare required or default", fieldPath)
			}
			if described {
				return fmt.Errorf("%s: envdoc is only supported on value fields", fieldPath)
			}
			segment := name
			if segment == "" && !field.Anonymous {
				segment = envSegment(field.Name)
			}
			nextPrefix := prefix
			if segment != "" {
				if !validEnvKey(segment) {
					return fmt.Errorf("%s: env segment %q is not a valid shell variable name", fieldPath, segment)
				}
				nextPrefix = prefix + segment + "_"
			}
			if err := collectEnv(fieldType, nextPrefix, fieldPath, fieldIndex, fields, seen, visiting); err != nil {
				return err
			}
			continue
		}
		if name == "" {
			name = envSegment(field.Name)
		}
		if required && hasDefault {
			return fmt.Errorf("%s: required and default cannot be combined", fieldPath)
		}

		key := prefix + name
		if !validEnvKey(key) {
			return fmt.Errorf("%s: env key %q is not a valid shell variable name", fieldPath, key)
		}
		if strings.ContainsAny(defaultValue, "\r\n") {
			return fmt.Errorf("%s: default must not contain a newline", fieldPath)
		}
		if strings.IndexByte(defaultValue, 0) >= 0 {
			return fmt.Errorf("%s: default must not contain NUL", fieldPath)
		}
		if previous, ok := seen[key]; ok {
			return fmt.Errorf("%s duplicates env %s declared by %s", fieldPath, key, previous)
		}
		seen[key] = fieldPath
		*fields = append(*fields, envField{
			key:         key,
			value:       defaultValue,
			required:    required,
			hasDefault:  hasDefault,
			description: description,
			path:        fieldPath,
			index:       fieldIndex,
			typ:         field.Type,
		})
	}
	return nil
}

func normalizeEnvPrefix(value string) (string, error) {
	raw := strings.TrimSpace(value)
	if raw == "" {
		return "", nil
	}
	prefix := strings.TrimRight(raw, "_")
	if prefix == "" || !validEnvKey(prefix) {
		return "", fmt.Errorf("env prefix %q is not a valid shell variable prefix", value)
	}
	return prefix + "_", nil
}

func envSegment(fieldName string) string {
	runes := []rune(fieldName)
	var out strings.Builder
	out.Grow(len(fieldName))
	for i, char := range runes {
		if i > 0 && unicode.IsUpper(char) {
			previous := runes[i-1]
			nextLower := i+1 < len(runes) && unicode.IsLower(runes[i+1])
			if unicode.IsLower(previous) || unicode.IsDigit(previous) || unicode.IsUpper(previous) && nextLower {
				out.WriteByte('_')
			}
		}
		out.WriteRune(unicode.ToUpper(char))
	}
	return out.String()
}

func loadEnvField(ctx context.Context, root reflect.Value, field envField) error {
	actual, found := readEnvField(root, field.index)
	holderType := reflect.StructOf([]reflect.StructField{{
		Name: "Value",
		Type: field.typ,
		Tag:  reflect.StructTag("env:" + strconv.Quote(envFieldTag(field))),
	}})
	holder := reflect.New(holderType)
	if found {
		holder.Elem().Field(0).Set(actual)
	}
	if err := envconfig.ProcessWith(ctx, &envconfig.Config{
		Target:   holder.Interface(),
		Lookuper: envconfig.OsLookuper(),
	}); err != nil {
		return fmt.Errorf("load environment %s (%s): %w", field.key, field.path, err)
	}
	decoded := holder.Elem().Field(0)
	if found {
		actual.Set(decoded)
		return nil
	}
	if decoded.IsZero() {
		return nil
	}
	writeEnvField(root, field.index, decoded)
	return nil
}

func envFieldTag(field envField) string {
	tag := field.key
	if field.required {
		tag += ",required"
	}
	if field.hasDefault {
		tag += ",default=" + field.value
	}
	return tag
}

func readEnvField(root reflect.Value, index []int) (reflect.Value, bool) {
	value := root
	for _, fieldIndex := range index {
		for value.Kind() == reflect.Pointer {
			if value.IsNil() {
				return reflect.Value{}, false
			}
			value = value.Elem()
		}
		if value.Kind() != reflect.Struct {
			return reflect.Value{}, false
		}
		value = value.Field(fieldIndex)
	}
	return value, value.IsValid()
}

func writeEnvField(root reflect.Value, index []int, value reflect.Value) {
	current := root
	for i, fieldIndex := range index {
		for current.Kind() == reflect.Pointer {
			if current.IsNil() {
				current.Set(reflect.New(current.Type().Elem()))
			}
			current = current.Elem()
		}
		if i == len(index)-1 {
			current.Field(fieldIndex).Set(value)
			return
		}
		current = current.Field(fieldIndex)
	}
}

func validateEnvValues(config any, schema envSchema) (err error) {
	defer func() {
		if recovered := recover(); recovered != nil {
			err = fmt.Errorf("validate environment: %v", recovered)
		}
	}()
	if err := envValidator.Struct(config); err != nil {
		return formatEnvValidationError(err, schema)
	}
	return nil
}

var envValidator = validator.New(validator.WithRequiredStructEnabled())

func formatEnvValidationError(err error, schema envSchema) error {
	var validationErrors validator.ValidationErrors
	if !errors.As(err, &validationErrors) {
		return fmt.Errorf("validate environment: %w", err)
	}
	messages := make([]string, 0, len(validationErrors))
	for _, fieldError := range validationErrors {
		location := envFieldKey(schema.fields, fieldError.StructNamespace())
		if location == "" {
			location = fieldError.StructNamespace()
		}
		if location == "" {
			location = fieldError.Field()
		}
		rule := fieldError.Tag()
		if param := fieldError.Param(); param != "" {
			rule += "=" + param
		}
		messages = append(messages, fmt.Sprintf("%s: failed validate:%q", location, rule))
	}
	return fmt.Errorf("validate environment: %s", strings.Join(messages, "; "))
}

func envFieldKey(fields []envField, structNamespace string) string {
	for _, field := range fields {
		if structNamespace == field.path || strings.HasSuffix(structNamespace, "."+field.path) {
			return field.key
		}
	}
	return ""
}

func derefEnvType(t reflect.Type) (reflect.Type, error) {
	seen := map[reflect.Type]struct{}{}
	for t.Kind() == reflect.Pointer {
		if _, ok := seen[t]; ok {
			return nil, fmt.Errorf("recursive pointer type %s", t)
		}
		seen[t] = struct{}{}
		t = t.Elem()
	}
	return t, nil
}

func envPathError(path string, err error) error {
	if path == "" {
		return err
	}
	return fmt.Errorf("%s: %w", path, err)
}

func implementsEnvDecoder(t reflect.Type) bool {
	pointer := reflect.PointerTo(t)
	for _, decoderType := range envDecoderTypes {
		if t.Implements(decoderType) || pointer.Implements(decoderType) {
			return true
		}
	}
	return false
}

func parseEnvTag(tag string) (name string, required, hasDefault bool, defaultValue, prefix string, err error) {
	if tag == "" {
		return "", false, false, "", "", nil
	}
	name, rest, hasOptions := strings.Cut(tag, ",")
	name = strings.TrimSpace(name)
	if !hasOptions {
		return name, false, false, "", "", nil
	}
	if rest == "" {
		return "", false, false, "", "", fmt.Errorf("empty env option")
	}

	for rest != "" {
		var rawOption string
		rawOption, rest, _ = strings.Cut(rest, ",")
		option := strings.TrimLeftFunc(rawOption, unicode.IsSpace)
		keyword := strings.TrimSpace(option)
		switch {
		case keyword == "":
			return "", false, false, "", "", fmt.Errorf("empty env option")
		case strings.EqualFold(keyword, "required"):
			if required {
				return "", false, false, "", "", fmt.Errorf("duplicate required option")
			}
			required = true
		case strings.HasPrefix(strings.ToLower(option), "prefix="):
			if prefix != "" {
				return "", false, false, "", "", fmt.Errorf("duplicate prefix option")
			}
			prefix = option[len("prefix="):]
			if prefix == "" {
				return "", false, false, "", "", fmt.Errorf("prefix is empty")
			}
		case strings.HasPrefix(strings.ToLower(option), "default="):
			if hasDefault {
				return "", false, false, "", "", fmt.Errorf("duplicate default option")
			}
			hasDefault = true
			defaultValue = option[len("default="):]
			if rest != "" {
				if containsEnvOption(rest) {
					return "", false, false, "", "", fmt.Errorf("default must be the last env option")
				}
				defaultValue += "," + rest
			}
			return name, required, hasDefault, defaultValue, prefix, nil
		default:
			return "", false, false, "", "", fmt.Errorf("unknown env option %q", option)
		}
	}
	return name, required, hasDefault, defaultValue, prefix, nil
}

func containsEnvOption(value string) bool {
	for _, option := range strings.Split(value, ",") {
		option = strings.TrimSpace(option)
		switch {
		case strings.EqualFold(option, "required"),
			strings.HasPrefix(strings.ToLower(option), "prefix="),
			strings.HasPrefix(strings.ToLower(option), "default="):
			return true
		}
	}
	return false
}

func validEnvKey(key string) bool {
	if key == "" {
		return false
	}
	for i := 0; i < len(key); i++ {
		char := key[i]
		if char == '_' || char >= 'a' && char <= 'z' || char >= 'A' && char <= 'Z' {
			continue
		}
		if i > 0 && char >= '0' && char <= '9' {
			continue
		}
		return false
	}
	return true
}

func quoteEnvValue(value string) string {
	if value == "" {
		return ""
	}
	for i := 0; i < len(value); i++ {
		char := value[i]
		if char >= 'a' && char <= 'z' || char >= 'A' && char <= 'Z' || char >= '0' && char <= '9' {
			continue
		}
		switch char {
		case '_', '.', '/', ':', '@', '%', '+', ',', '-', '=':
			continue
		}
		return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'"
	}
	return value
}

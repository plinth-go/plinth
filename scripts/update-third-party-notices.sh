#!/usr/bin/env bash
set -euo pipefail

root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$root"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

./scripts/go-licenses.sh report --include_tests ./... >"$tmp"

{
	cat <<'EOF'
# Third-Party Notices

Plinth is licensed under the Apache License 2.0. The following table lists the
third-party Go packages reachable from this repository and the license
information reported by `go-licenses`. Test-only packages are included.
The report uses the Linux package set so CI output is reproducible.

This file is generated by `make license-update`; do not edit it by hand.

| Package | License | License source |
| --- | --- | --- |
EOF
	awk -F, 'NR > 1 && $1 != "github.com/plinth-go/plinth" { printf "| `%s` | %s | [source](%s) |\n", $1, $3, $2 }' "$tmp" | LC_ALL=C sort -u
} >THIRD_PARTY_NOTICES.md
